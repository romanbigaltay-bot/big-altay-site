<?php
/**
 * ============================================================================
 * Big Altay Design System (BADS)
 * UI / Stars
 * ============================================================================
 */

$args = wp_parse_args($args ?? [], [

    /*
    |--------------------------------------------------------------------------
    | Content
    |--------------------------------------------------------------------------
    */

    'value' => 0,

    /*
    |--------------------------------------------------------------------------
    | Appearance
    |--------------------------------------------------------------------------
    */

    'size' => 'md',

    /*
    |--------------------------------------------------------------------------
    | HTML
    |--------------------------------------------------------------------------
    */

    'class' => '',

]);

$count = max(0, (int) $args['value']);

if (!$count) {
    return;
}

$classes = [
    'bads-stars',
    'bads-stars--' . sanitize_html_class($args['size']),
];

if (!empty($args['class'])) {
    $classes[] = sanitize_html_class($args['class']);
}

?>

<div class="<?= esc_attr(implode(' ', $classes)); ?>">

    <?php for ($i = 0; $i < $count; $i++) : ?>

        <?php
        get_template_part(
            'template-parts/ui/icon',
            null,
            [
                'name'  => 'star',
                'size'  => $args['size'],
                'class' => 'bads-stars__icon',
            ]
        );
        ?>

    <?php endfor; ?>

</div>