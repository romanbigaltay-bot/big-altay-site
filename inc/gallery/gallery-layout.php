/*
|--------------------------------------------------------------------------
| Segment Definitions
|--------------------------------------------------------------------------
*/

const BADS_GALLERY_SEGMENTS = [
    'a' => [
        'slots' => 4,
        // Порядок: большой слева (2x2), малый справа (1x1), высокий справа (1x2), широкий снизу (2x1)
        'items' => ['2x2', '1x1', '1x2', '2x1'], 
    ],
    'b' => [
        'slots' => 4,
        // Зеркально. Порядок важен для dense-сетки: сначала малый (1x1), потом большой (2x2) улетит вправо!
        'items' => ['1x1', '2x2', '1x2', '2x1'], 
    ],
    'c' => [
        'slots' => 2,
        'items' => ['1x1', '2x1'],
    ],
    'd' => [
        'slots' => 3,
        // Порядок: большой слева (2x2), и два малых справа (1x1, 1x1)
        'items' => ['2x2', '1x1', '1x1'],
    ],
];

/*
|--------------------------------------------------------------------------
| Builder
|--------------------------------------------------------------------------
*/

function bads_gallery_build_layout(array $images): array
{

    /*
    |--------------------------------------------------------------------------
    | Segment Combinations
    |--------------------------------------------------------------------------
    */

    $maps = [

        2 => ['c'],

        3 => ['d'],

        4 => ['a'],

        5 => ['d', 'c'],

        6 => ['a', 'c'],

        7 => ['a', 'd'],

        8 => ['a', 'b'],

    ];

    $segments = [];

    $count = count($images);

    $offset = 0;

    while ($count > 0) {

        /*
        --------------------------------------------------------------
        | Find Best Combination
        --------------------------------------------------------------
        */

        if (isset($maps[$count])) {

            $types = $maps[$count];

        } else {

            /*
            ----------------------------------------------------------
            | 9+
            ----------------------------------------------------------
            */

            $types = [

                count($segments) % 2 === 0
                    ? 'a'
                    : 'b',

            ];

        }

        foreach ($types as $type) {

            $definition = BADS_GALLERY_SEGMENTS[$type];

            $items = [];

            foreach ($definition['items'] as $shape) {

                $items[] = [

                    'shape' => $shape,

                    'image' => $images[$offset],

                ];

                $offset++;

            }

            $segments[] = [

                'type'  => $type,

                'items' => $items,

            ];

            $count -= count($definition['items']);

        }

    }

    return $segments;

}